def run_guideline_debugger_clustering(db: Session, brand_id: Optional[str] = None) -> List[GuidelineInsight]:
    """
    Guideline Clarity Radar Engine:
    Analyzes historical review findings, creator decisions, and suggestion overrides.
    Discovers recurring error clusters, isolated rule ambiguities, and stale evidence.
    Creates or updates real GuidelineInsight and ProposedGuidelineClarification records.
    """
    findings = db.query(Finding).all()
    if not findings:
        return []

    jobs = {j.id: (j.document_id, j.brand_id) for j in db.query(ReviewJob.id, ReviewJob.document_id, ReviewJob.brand_id).all()}

    # Group findings by rule_id
    clusters_by_rule = defaultdict(list)
    for f in findings:
        if f.rule_id:
            job_info = jobs.get(f.review_job_id, ("unknown-doc", None))
            doc_id = job_info[0]
            doc_brand = job_info[1]
            if brand_id and doc_brand and doc_brand != brand_id:
                continue
            clusters_by_rule[f.rule_id].append((f, doc_id))

    # Also detect frequent overrides from SuggestionDecision records
    rejected_decisions = db.query(SuggestionDecision).filter(SuggestionDecision.action == "rejected").all()
    overridden_finding_ids = set([d.finding_id for d in rejected_decisions])

    insights = []

    for rule_id, items in clusters_by_rule.items():
        count = len(items)
        if count < 2:
            continue  # Requires recurring evidence across drafts

        rule = db.query(BrandGuideline).filter(BrandGuideline.id == rule_id).first()
        fact = None
        evidence = None
        if not rule:
            fact = db.query(ApprovedFact).filter(ApprovedFact.id == rule_id).first()
        if not rule and not fact:
            evidence = db.query(BrandEvidence).filter(BrandEvidence.id == rule_id).first()

        finding_ids = [item[0].id for item in items]
        document_ids = list(set([item[1] for item in items]))
        quotes = [f'"{item[0].affected_text}"' for item in items[:4]]
        quotes_summary = ", ".join(quotes)

        # Check how many times findings for this rule were rejected/overridden by creators
        override_count = sum(1 for item in items if item[0].id in overridden_finding_ids or item[0].creator_decision == "rejected")

        # Determine pattern type and root cause
        if override_count >= 1:
            title = f"High Override Rate for Rule '{rule_id}'"
            pattern_type = "frequent_override"
            root_cause = (
                f"Creators frequently rejected findings generated by rule '{rule_id}' ({override_count} overrides). "
                f"Writers cited feedback that this rule is overly restrictive, contextually misapplied, "
                f"or in conflict with current campaign requirements."
            )
            suggested_action = (
                f"Review rule '{rule_id}' with the content and compliance team to relax or provide explicit exception contexts."
            )
            current_text = rule.rule_text if rule else (evidence.approved_wording if evidence else "")
            proposed_clarification = f"{current_text} EXCEPTION CONTEXT: Permitted in top-of-funnel social content with clear qualification."

        elif rule and ("claim" in rule.category.lower() or "guarantee" in rule.rule_text.lower()):
            title = f"Recurring Guarantee Violations Linked to '{rule.title}'"
            pattern_type = "vague_guideline"
            root_cause = (
                f"The promotional claim guideline '{rule_id}' encourages bold, persuasive messaging, "
                f"but lacks an explicit boundary regarding absolute guarantees or unverified outcome claims. "
                f"Writers repeatedly interpret 'be bold' as permission to state guaranteed results ({quotes_summary})."
            )
            suggested_action = (
                f"Clarify '{rule_id}' boundary: explicitly prohibit absolute terms like 'guaranteed results', "
                f"'100% effective', and 'miracle' unless accompanied by a verified clinical or audit evidence record."
            )
            proposed_clarification = (
                f"{rule.rule_text} "
                f"BOUNDARY CLARIFICATION (v{rule.version + 1}): Do not promise guaranteed outcomes, 100% success rates, "
                f"or risk-free results unless an approved evidence record in the Brand Evidence Ledger explicitly permits the claim."
            )

        elif (fact and "price" in fact.category.lower()) or (evidence and "price" in evidence.category.lower()):
            val = fact.canonical_value if fact else (evidence.structured_value if evidence else "")
            title = f"Repeated Outdated Pricing Citations for '{rule_id}'"
            pattern_type = "outdated_fact"
            root_cause = (
                f"Multiple drafts repeatedly cite legacy pricing ({quotes_summary}). "
                f"Draft templates and sales collaterals have not been updated to reflect the canonical price schedule '{val}'."
            )
            suggested_action = (
                f"Update content templates to enforce canonical price '{val}' and flag legacy figures as deprecated."
            )
            proposed_clarification = (
                f"Enforce canonical pricing '{val}' across all marketing, sales, and web assets. "
                f"Deprecate references to legacy pricing tiers."
            )

        else:
            title = f"Clustered Compliance Deviations for Rule '{rule_id}'"
            pattern_type = "recurring_violation"
            root_cause = (
                f"Observed {count} recurring findings under '{rule_id}'. "
                f"Reviewers frequently flag phrases ({quotes_summary}), indicating that creators find the guidance ambiguous or difficult to apply."
            )
            suggested_action = (
                f"Review guideline '{rule_id}' with the editorial team and add concrete positive and negative examples."
            )
            current_text = rule.rule_text if rule else (evidence.approved_wording if evidence else "")
            proposed_clarification = f"{current_text} (Clarified: Ensure clear examples and boundaries are provided)."

        # Check if insight already exists for this rule
        existing_insight = db.query(GuidelineInsight).filter(GuidelineInsight.rule_id == rule_id).first()
        if existing_insight:
            existing_insight.occurrence_count = count
            existing_insight.supporting_finding_ids = finding_ids
            existing_insight.supporting_document_ids = document_ids
            existing_insight.evidence_summary = f"Identified in drafts citing: {quotes_summary}"
            existing_insight.updated_at = datetime.utcnow()
            insight = existing_insight
        else:
            insight = GuidelineInsight(
                workspace_id="default-workspace",
                brand_id=brand_id,
                title=title,
                rule_id=rule_id,
                suspected_root_cause=root_cause,
                pattern_type=pattern_type,
                occurrence_count=count,
                supporting_finding_ids=finding_ids,
                supporting_document_ids=document_ids,
                evidence_summary=f"Identified in drafts citing: {quotes_summary}",
                suggested_action=suggested_action,
                hypothesis_status="hypothesis",
                status_marking="under_investigation"
            )
            db.add(insight)
            db.flush()

        insights.append(insight)

        # Check or create draft clarification proposal
        existing_prop = db.query(ProposedGuidelineClarification).filter(
            ProposedGuidelineClarification.target_rule_id == rule_id,
            ProposedGuidelineClarification.approval_status == "pending"
        ).first()

        if not existing_prop and rule:
            prop = ProposedGuidelineClarification(
                insight_id=insight.id,
                target_rule_id=rule.id,
                current_rule_version=rule.version,
                proposed_version=rule.version + 1,
                original_rule_text=rule.rule_text,
                proposed_rule_text=proposed_clarification,
                clarification_summary=suggested_action,
                proposing_actor="Guideline Clarity Radar Engine",
                approval_status="pending"
            )
            db.add(prop)

    db.commit()
    return insights


def confirm_or_dismiss_hypothesis(
    db: Session,
    insight_id: str,
    action: str,  # "confirm" or "dismiss"
    notes: Optional[str] = None,
    status_marking: Optional[str] = None,
    user_name: str = "Admin",
    user_role: str = "reviewer"
) -> GuidelineInsight:
    insight = db.query(GuidelineInsight).filter(GuidelineInsight.id == insight_id).first()
    if not insight:
        raise ValueError(f"Insight '{insight_id}' not found")

    if action.lower() in ("confirm", "confirmed"):
        insight.hypothesis_status = "confirmed"
        insight.status_marking = status_marking or "needs_clarification"
    else:
        insight.hypothesis_status = "dismissed"
        insight.status_marking = status_marking or "not_an_issue"

    insight.decision_notes = notes
    insight.reviewed_by = f"{user_name} ({user_role})"
    insight.reviewed_at = datetime.utcnow()
    insight.updated_at = datetime.utcnow()
    db.commit()
    db.refresh(insight)

    log_audit_event(
        db=db,
        event_type="HYPOTHESIS_EVALUATED",
        actor_id=user_name,
        actor_name=user_name,
        actor_role=user_role,
        target_type="insight",
        target_id=insight.id,
        summary=f"Clarity Radar insight '{insight.id}' marked '{insight.hypothesis_status}' by {user_name} ({user_role})"
    )
    return insight

def approve_guideline_clarification(
    db: Session,
    proposal_id: str,
    brand_owner_name: str,
    edited_rule_text: Optional[str] = None,
    notes: Optional[str] = None
) -> Tuple[BrandGuideline, ProposedGuidelineClarification]:
    proposal = db.query(ProposedGuidelineClarification).filter(
        ProposedGuidelineClarification.id == proposal_id
    ).first()
    if not proposal:
        raise ValueError(f"Clarification proposal '{proposal_id}' not found")

    rule = db.query(BrandGuideline).filter(BrandGuideline.id == proposal.target_rule_id).first()
    if not rule:
        raise ValueError(f"Target rule '{proposal.target_rule_id}' not found")

    final_text = edited_rule_text or proposal.proposed_rule_text

    # Substantive update: increment version
    rule.rule_text = final_text
    rule.version += 1
    rule.clarification_notes = notes or proposal.clarification_summary
    rule.updated_at = datetime.utcnow()

    # Update proposal record
    proposal.approval_status = "approved"
    proposal.reviewer_notes = notes
    proposal.reviewed_by = brand_owner_name
    proposal.reviewed_at = datetime.utcnow()

    # If linked to an insight, mark as updated/resolved
    if proposal.insight_id:
        ins = db.query(GuidelineInsight).filter(GuidelineInsight.id == proposal.insight_id).first()
        if ins:
            ins.status_marking = "updated"
            ins.updated_at = datetime.utcnow()

    db.commit()
    db.refresh(rule)
    db.refresh(proposal)

    log_audit_event(
        db=db,
        event_type="CLARIFICATION_APPROVED",
        actor_id=brand_owner_name,
        actor_name=brand_owner_name,
        actor_role="brand_owner",
        target_type="rule",
        target_id=rule.id,
        summary=f"Brand Owner {brand_owner_name} approved clarification for '{rule.id}'. Updated to v{rule.version}.",
        details={"proposal_id": proposal.id, "new_rule_text": rule.rule_text}
    )

    return rule, proposal
